"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const source=fs.readFileSync(path.join(__dirname,"../game/src/world/0064-city-rules.js"),"utf8");
const context={};vm.createContext(context);
vm.runInContext(source,context);const plan=context.planUrbanParcel51;
assert.equal(typeof plan,"function","Debe existir un planificador no destructivo");
const site={x:20,z:18,w:10,d:10},home={x:20,y:18,w:5,d:5,h:3,type:"casa"},other={x:45,y:18,w:7,d:7,type:"Vivienda34 · original"};
const box=[17.8,15.8,22.2,20.2],protectedSites=[{x:100,z:100,radius:10}],roads=[{axis:"z",center:37,min:-100,max:100,width:8}];
const snapshot=JSON.stringify({site,home,other,box});
const vacancy=plan(site,[],[],roads,protectedSites);
assert(vacancy.approved&&vacancy.replacements.length===0,"Se permiten solares despejados");
const refused=plan(site,[home,other],[box],roads,protectedSites);
assert.equal(refused.reason,"unapproved-home","Nunca borrar una casa sin seleccionar el objetivo");
const approved=plan({...site,replaceIndices:[0]},[home,other],[box],roads,protectedSites);
assert(approved.approved&&approved.replacements.length===1,"Sustitución precisa de una casa aprobada");
assert.equal(approved.replacements[0].index,0);
assert.equal(approved.replacements[0].type,"casa");
const unseen=plan({...site,replaceIndices:[1]},[home,other],[box],roads,protectedSites);
assert.equal(unseen.reason,"unapproved-home","La autorización para otra casa no equivale a esta");
const alien=plan({...site,replaceIndices:[0]},[home,other,[/*ignored*/]], [box,[22.5,21.5,25.5,24.5]],roads,protectedSites);
assert.equal(alien.reason,"unowned-collision","No quitar colisiones ajenas");
const partial=plan({x:20,z:18,w:4,d:4,replaceIndices:[0]},[home],[box],roads,protectedSites);
assert.equal(partial.reason,"partial-home","Nunca demoler media casa");
const landmark=plan({x:100,z:100,w:8,d:8},[],[],roads,protectedSites);
assert.equal(landmark.reason,"protected-landmark","Proteger los edificios emblemáticos");
const onRoad=plan({x:37,z:18,w:8,d:10},[],[],roads,protectedSites);
assert.equal(onRoad.reason,"road-conflict","Ni la autorización de obra permite invadir carriles");
const broad=plan({...site,replaceIndices:[0]},[{...home,type:"Palacio histórico"}],[box],roads,protectedSites);
assert.equal(broad.reason,"other-building","Ni permitir borrar casas equivale a borrar monumentos");
const unmatched=plan({...site,replaceIndices:[4]},[],[],roads,protectedSites);
assert.equal(unmatched.reason,"unmatched-replacement","Un reemplazo debe identificar una vivienda real");
assert.equal(JSON.stringify({site,home,other,box}),snapshot,"Nunca mutar los datos del mundo desde un plan preliminar");
assert(!/\.splice\(|\.dispose\(|\.delete\(/.test(source.slice(source.indexOf("function planUrbanParcel51("))),"El planificador no debe borrar viviendas ni mallas por sí mismo");
console.log("MANAGUA_PARCELS_OK "+JSON.stringify({housesApproved:1,preservedNeighbours:true,protectedLandmarks:true,nonDestructive:true}));
