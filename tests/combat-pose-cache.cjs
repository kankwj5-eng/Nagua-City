"use strict";
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm"),assert=require("node:assert/strict");
const source=fs.readFileSync(path.join(__dirname,"../game/src/characters/0182-install-combat-pose29.js"),"utf8");
const track=[];
const node=name=>({name,disposed:false,isDisposed(){return this.disposed;},rotationQuaternion:{multiplyInPlace(q){track.push([name,+q.angle.toFixed(4)]);}}});
let rig=["upperarm_l","lowerarm_l","upperarm_r","lowerarm_r"].map(node),traversals=0,bases=0;
const p={root:{getDescendants(){traversals++;return rig;}},equipment:{rotationQuaternion:{multiplyInPlace(q){track.push(["recoil",+q.angle.toFixed(4)]);}}}};
const c={equipped:"hands",ammo:{rifle:{},pistol:{}},city:{state:{block:false}},expansion29:{combat:{lastHand:"r"}},actionTimer:0,
 updateEquipmentPose(){bases++;},B:{Quaternion:{RotationAxis(_,angle){return {angle};}}},V(){return {};},Math};
vm.createContext(c);
vm.runInContext(source+"\ninstallCombatPose29();",c);
const step=()=>c.updateEquipmentPose(p,1/60);
step();assert.equal(traversals,0,"idle combat must not enumerate bones");
c.city.state.block=true;
step();assert.deepEqual(track.slice(-2),[["upperarm_l",-.82],["lowerarm_l",-.58]]);
const first=traversals;assert.equal(first,2);
step();assert.equal(traversals,first,"block pose uses cached bones");
c.city.state.block=false;c.equipped="rifle";
step();assert.equal(traversals,first,"rifle reuses left-arm bones discovered by block pose");
assert.deepEqual(track.slice(-2),[["upperarm_l",-.72],["lowerarm_l",-.65]]);
c.equipped="pistol";c.actionTimer=.19;step();
assert.equal(traversals,first,"pistol recoil does not need a skeleton scan");
assert.deepEqual(track.at(-1),["recoil",-.1]);
c.equipped="rifle";c.actionTimer=0;
rig.forEach(x=>x.disposed=true);
rig=["upperarm_l","lowerarm_l","upperarm_r","lowerarm_r"].map(node);
step();
assert.equal(traversals,first+2,"disposed bones must be refreshed after a rig rebuild");
assert.deepEqual(track.slice(-2),[["upperarm_l",-.72],["lowerarm_l",-.65]]);
assert.equal(bases,6,"original base pose is still called on every frame");
console.log("COMBAT_POSE_CACHE_OK "+JSON.stringify({baseCalls:bases,firstLookups:first,subsequentRepeatedLookups:0,rigRecoveryLookups:2}));
